export const videoPageBySlug = (slug: string) => videoPages.find((video) => video.slug === slug);
export const videoPageUrl = (slug: string) => `/video/${slug}`;
export const videosByGroup = (group: VideoGroup) => videoPages.filter((video) => video.group === group);

export function videoPageForSource(provider: VideoProvider, providerId: string, title?: string) {
  const matches = videoPages.filter((video) => video.provider === provider && video.providerId === providerId);
  if (title && matches.length > 1) {
    const exactTitleMatch = matches.find((video) => video.title.toLocaleLowerCase("ru-RU").includes(title.toLocaleLowerCase("ru-RU")) || title.toLocaleLowerCase("ru-RU").includes(video.title.toLocaleLowerCase("ru-RU")));
    if (exactTitleMatch) return exactTitleMatch;
  }
  return matches[0];
}
